public class Calculadora {
    public static void main(String[] args) {
        int primerNumero = 18;
        int segundoNumero = 7;
        int tercerNumero = 6; 

        System.out.println("Suma: " + (primerNumero + segundoNumero + tercerNumero));
        System.out.println("Resta: " + (primerNumero - segundoNumero - tercerNumero));
        System.out.println("Multiplicación: " + (primerNumero * segundoNumero * tercerNumero));
    }
}